// copperflow workspace: the hosted Studio and the hosted MCP server for ONE project folder, as the hub's runner starts
// them. The only secret-free input it reads from its environment is the hub's public ticket key; everything else is
// on the command line, so the process holds nothing worth stealing (docs/hosted.md, rule 7).
import type { KeyObject } from "node:crypto"
import { resolve } from "node:path"
import type { DesignSource } from "../core/bom.js"
import { createCopperflowServer } from "../mcp/server.js"
import { startStudio, type StudioOptions } from "../studio/server.js"
import { normaliseBasePath, normaliseOrigin } from "./gate.js"
import { startMcpHttp } from "./mcp-http.js"
import { ticketPublicKeyFromEnv, TICKET_PUBLIC_KEY_ENV } from "./ticket.js"

export interface WorkspaceOptions {
  root: string
  id: string
  publicOrigin: string
  basePath: string
  /** 0 picks a free port. */
  studioPort: number
  /** 0 picks a free port. */
  mcpPort: number
  bind: string
  ticketPublicKey: KeyObject
}

export interface Workspace {
  /** The Studio's private origin, such as http://127.0.0.1:41234. */
  studio: string
  /** The MCP server's private origin; it serves at /mcp. */
  mcp: string
  close(): Promise<void>
}

/** What tests may swap: the Studio's builder and workers, the MCP server's engine. */
export interface WorkspaceExtras {
  studio?: Pick<StudioOptions, "builder" | "routeWorker" | "placeWorker" | "staticDir">
  engine?: DesignSource
}

/** Workspace ids are generated by the hub: lower-case letters, digits and dashes. */
export const WORKSPACE_ID = /^[a-z0-9][a-z0-9-]{0,63}$/

const USAGE =
  "Usage: copperflow workspace --root <folder> --id <workspace id> --public-origin <origin> --base-path </p/...> --studio-port <n> --mcp-port <n> [--bind 127.0.0.1] [--stop-on-stdin-end]"

function portOf(text: string | undefined, name: string): number {
  const value = Number(text)
  if (text === undefined || !Number.isInteger(value) || value < 0 || value > 65_535) throw new Error(`${name} must be a port number from 0 to 65535. ${USAGE}`)
  return value
}

/**
 * The options from the command line and the one environment variable it reads, COPPERFLOW_TICKET_PUBLIC_KEY. Every
 * value is checked before anything listens.
 */
export function parseWorkspaceArgs(args: readonly string[], cwd: string, env: NodeJS.ProcessEnv): { options: WorkspaceOptions; stopOnStdinEnd: boolean } {
  const values = new Map<string, string>()
  let stopOnStdinEnd = false
  const known = new Set(["--root", "--id", "--public-origin", "--base-path", "--studio-port", "--mcp-port", "--bind"])
  for (let i = 0; i < args.length; i += 1) {
    const arg = args[i] as string
    if (arg === "--stop-on-stdin-end") {
      stopOnStdinEnd = true
      continue
    }
    if (!known.has(arg)) throw new Error(`Unknown workspace option "${arg}". ${USAGE}`)
    if (values.has(arg)) throw new Error(`${arg} is given twice. ${USAGE}`)
    const value = args[i + 1]
    if (value === undefined || value === "") throw new Error(`Missing ${arg} value. ${USAGE}`)
    values.set(arg, value)
    i += 1
  }
  const need = (name: string) => {
    const value = values.get(name)
    if (value === undefined) throw new Error(`Missing ${name}. ${USAGE}`)
    return value
  }
  const id = need("--id")
  if (!WORKSPACE_ID.test(id)) throw new Error("--id must be lower-case letters, digits and dashes (at most 64)")
  const basePath = normaliseBasePath(need("--base-path"))
  if (!basePath.startsWith("/p/")) throw new Error("--base-path must start with /p/")
  const ticketPublicKey = ticketPublicKeyFromEnv({ [TICKET_PUBLIC_KEY_ENV]: env[TICKET_PUBLIC_KEY_ENV] })
  return {
    stopOnStdinEnd,
    options: {
      root: resolve(cwd, need("--root")),
      id,
      publicOrigin: normaliseOrigin(need("--public-origin")),
      basePath,
      studioPort: portOf(values.get("--studio-port"), "--studio-port"),
      mcpPort: portOf(values.get("--mcp-port"), "--mcp-port"),
      bind: values.get("--bind") ?? "127.0.0.1",
      ticketPublicKey,
    },
  }
}

/** Starts both servers; if the second fails, the first is closed again. */
export async function startWorkspace(options: WorkspaceOptions, extras: WorkspaceExtras = {}): Promise<Workspace> {
  const hosted = { bind: options.bind, publicOrigin: options.publicOrigin, basePath: options.basePath, workspaceId: options.id, ticketPublicKey: options.ticketPublicKey }
  const studio = await startStudio({ root: options.root, port: options.studioPort, hosted, ...(extras.studio ?? {}) })
  let mcp
  try {
    mcp = await startMcpHttp({
      port: options.mcpPort,
      bind: options.bind,
      makeServer: () => createCopperflowServer(options.root, { hosted: true, ...(extras.engine ? { engine: extras.engine } : {}) }),
      ticket: { publicKey: options.ticketPublicKey, workspaceId: options.id },
      publicOrigin: options.publicOrigin,
    })
  } catch (error) {
    await studio.close()
    throw error
  }
  const served = mcp
  return {
    studio: studio.url,
    mcp: new URL(served.url).origin,
    close: async () => {
      await Promise.allSettled([studio.close(), served.close()])
    },
  }
}
